CREATE TABLE asr.hotel_zone_data
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    classification        INTEGER                                 NOT NULL,
    global_rate           DOUBLE PRECISION                        NOT NULL,
    occupancy_rate        DOUBLE PRECISION,
    opening_days_per_week INTEGER,
    room_types            JSONB                                   NOT NULL,
    room_counts           JSONB,
    management_package    JSONB,
    CONSTRAINT pk_hotelzonedata PRIMARY KEY (id)
);