CREATE TABLE asr.profile
(
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at       TIMESTAMP WITHOUT TIME ZONE,
    last_modified_at TIMESTAMP WITHOUT TIME ZONE,
    email            VARCHAR(255)                             NOT NULL,
    password         VARCHAR(255)                             NOT NULL,
    company          VARCHAR(255)                             NOT NULL,
    role             VARCHAR(255)                             NOT NULL,
    enabled          BOOLEAN                                  NOT NULL,
    manager_id       INTEGER,
    CONSTRAINT pk_profile PRIMARY KEY (id)
);

ALTER TABLE asr.profile
    ADD CONSTRAINT uc_profile_email UNIQUE (email);

ALTER TABLE asr.profile
    ADD CONSTRAINT uc_profile_manager UNIQUE (manager_id);

ALTER TABLE asr.profile
    ADD CONSTRAINT FK_PROFILE_ON_MANAGER FOREIGN KEY (manager_id) REFERENCES asr.profile (id) ON DELETE SET NULL;

CREATE INDEX idx_profile_email ON asr.profile (email);
CREATE INDEX idx_profile_manager_id ON asr.profile (manager_id);